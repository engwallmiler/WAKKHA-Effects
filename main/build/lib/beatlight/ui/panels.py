from PySide6.QtCore import Qt
from PySide6.QtWidgets import (QButtonGroup, QComboBox, QDoubleSpinBox, QFormLayout,
    QFrame, QHBoxLayout, QPushButton, QSpinBox, QSplitter, QTextEdit, QVBoxLayout, QWidget, QScrollArea)
from beatlight.ui.components import card, label, metric
from beatlight.ui.plots import StereoMeter, WaveformWidget
from beatlight.ui.dsp_settings import build_dsp_settings
from beatlight.ui.kick_settings import build_kick_settings
from beatlight.ui.beat_settings import build_beat_settings


def build_sidebar(self):
    sidebar = QFrame()
    sidebar.setObjectName("sidebar")
    sidebar.setFixedWidth(214)
    layout = QVBoxLayout(sidebar)
    layout.setContentsMargins(20, 30, 18, 22)
    layout.setSpacing(9)
    layout.addWidget(label("BEATLIGHT", "brand"))
    layout.addWidget(label("PIXELS  /  MUSIC TO LIGHT", "eyebrow"))
    layout.addSpacing(38)
    layout.addWidget(label("WORKSPACE", "eyebrow"))
    group = QButtonGroup(self)
    self.nav_group = group
    for index, text in ((9, "▥   Pixel Studio · LEDs"), (0, "◉   Audio Monitor"), (8, "⇄   Ableton Link"), (5, "◷   Rhythm Monitor"), (4, "●   Kick Monitor"), (3, "∿   Análise espectral"), (6, "◇   Lighting Studio"), (7, "▱   Stage Preview"), (1, "▥   Diagnósticos"), (2, "⚙   Configurações")):
        button = QPushButton(text)
        button.setObjectName("nav")
        button.setCheckable(True)
        button.setChecked(index == 0)
        group.addButton(button, index)
        button.clicked.connect(lambda checked=False, i=index: self._navigate(i))
        layout.addWidget(button)
    layout.addSpacing(30)
    layout.addWidget(label("PRÓXIMAS FASES", "eyebrow"))
    for name in ("Múltiplas saídas USB", "Mapeamento de instalações", "Controladores em rede"):
        item = label("   " + name, "muted")
        item.setContentsMargins(0, 7, 0, 7)
        layout.addWidget(item)
    layout.addStretch()
    layout.addWidget(label("PIXEL STUDIO · USB", "eyebrow"))
    layout.addWidget(label("Captura primeiro.\nLuz no tempo certo.", "subtitle", True))
    return sidebar


def build_monitor_page(self):
    page = QWidget()
    layout = QVBoxLayout(page)
    layout.setContentsMargins(0, 0, 0, 0)
    layout.setSpacing(14)
    source_card, source_layout = card("Entrada de áudio", "Selecione a saída usada pelo Traktor em WASAPI compartilhado.")
    row = QHBoxLayout()
    self.source_combo = QComboBox()
    self.source_combo.addItem("WASAPI Loopback", "wasapi")
    self.source_combo.addItem("Teste • sinal sintético", "synthetic")
    self.source_combo.addItem("Teste • breakdown e drop", "structure_demo")
    self.source_combo.addItem("Teste • baixo e densidade", "texture_demo")
    self.source_combo.setCurrentIndex(self.source_combo.findData(self.settings.source))
    self.source_combo.setMinimumWidth(180)
    self.source_combo.setAccessibleName("Tipo de fonte de áudio")
    self.source_combo.currentIndexChanged.connect(self._scan)
    self.device_combo = QComboBox()
    self.device_combo.setMinimumWidth(220)
    self.device_combo.setAccessibleName("Dispositivo de saída monitorado")
    self.device_combo.currentIndexChanged.connect(self._device_details)
    self.refresh_button = QPushButton("↻  Atualizar")
    self.refresh_button.clicked.connect(self._scan)
    row.addWidget(self.source_combo)
    row.addWidget(self.device_combo, 1)
    row.addWidget(self.refresh_button)
    source_layout.addLayout(row)
    controls = QHBoxLayout()
    controls.addWidget(label("BLOCO", "eyebrow"))
    self.block_combo = QComboBox()
    for size in (256, 512, 1024, 2048):
        self.block_combo.addItem(f"{size} frames", size)
    self.block_combo.setCurrentIndex((256, 512, 1024, 2048).index(self.settings.block_size))
    self.block_combo.setAccessibleName("Tamanho do bloco de captura")
    controls.addWidget(self.block_combo)
    self.device_info = label("Buscando dispositivos…", "muted")
    controls.addWidget(self.device_info, 1)
    self.start_button = QPushButton("▶  Iniciar captura")
    self.start_button.setObjectName("primary")
    self.start_button.clicked.connect(self._start)
    self.stop_button = QPushButton("■  Parar")
    self.stop_button.setObjectName("stop")
    self.stop_button.clicked.connect(self._stop_capture)
    self.stop_button.setEnabled(False)
    controls.addWidget(self.start_button)
    controls.addWidget(self.stop_button)
    source_layout.addLayout(controls)
    layout.addWidget(source_card)
    metrics = QHBoxLayout()
    self.metrics = {}
    for key, title, note in (("rate", "TAXA DE AMOSTRAGEM", "Formato efetivo da captura"),
                             ("channels", "CANAIS", "Float32 • sem normalização"),
                             ("block", "DURAÇÃO DO BLOCO", "Resolução temporal da entrada"),
                             ("age", "IDADE DO BLOCO", "Aquisição → apresentação • estimada")):
        frame, value = metric(title, note)
        self.metrics[key] = value
        metrics.addWidget(frame)
    layout.addLayout(metrics)
    splitter = QSplitter(Qt.Orientation.Horizontal)
    wave_card, wave_layout = card()
    wave_header = QHBoxLayout()
    wave_header.addWidget(label("Forma de onda", "section"))
    wave_header.addStretch()
    self.signal_badge = label("SEM CAPTURA", "badge")
    wave_header.addWidget(self.signal_badge)
    wave_layout.addLayout(wave_header)
    self.wave = WaveformWidget()
    wave_layout.addWidget(self.wave, 1)
    wave_layout.addWidget(label("●  Canal L     ●  Canal R        Janela de 200 ms · envelope min/max", "muted"))
    level_card, level_layout = card("Nível de entrada", "dBFS • escala −60 a 0")
    self.meter = StereoMeter()
    level_layout.addWidget(self.meter, 1)
    self.level_text = label("RMS —   /   PICO —", "muted", True)
    level_layout.addWidget(self.level_text)
    splitter.addWidget(wave_card)
    splitter.addWidget(level_card)
    splitter.setSizes([800, 220])
    layout.addWidget(splitter, 1)
    self.monitor_metrics = label("BLOCOS  0     ·     FILA  0     ·     DESCARTES  0     ·     DSP  —", "muted")
    layout.addWidget(self.monitor_metrics)
    self.notice = label("Loopback captura a mixagem da saída selecionada, incluindo outros aplicativos. Não captura ASIO nativo da Kontrol S4 MK2.", "notice", True)
    self.notice.setTextInteractionFlags(Qt.TextInteractionFlag.TextSelectableByMouse)
    layout.addWidget(self.notice)
    return page


def build_diagnostics_page(self):
    page = QWidget()
    layout = QVBoxLayout(page)
    layout.setContentsMargins(0, 0, 0, 0)
    info, info_layout = card("Operação em tempo real", "Métricas medidas; não representam uma garantia de latência com o Traktor.")
    self.diagnostic_values = label("Aguardando captura.", "subtitle", True)
    self.diagnostic_values.setTextInteractionFlags(Qt.TextInteractionFlag.TextSelectableByMouse)
    info_layout.addWidget(self.diagnostic_values)
    layout.addWidget(info)
    log_card, log_layout = card("Registro da sessão", "Erros e mudanças de estado • áudio bruto não é salvo")
    self.events = QTextEdit()
    self.events.setReadOnly(True)
    self.events.document().setMaximumBlockCount(500)
    log_layout.addWidget(self.events, 1)
    layout.addWidget(log_card, 1)
    button = QPushButton("Exportar diagnóstico JSON")
    button.clicked.connect(self._export_diagnostics)
    layout.addWidget(button, 0, Qt.AlignmentFlag.AlignRight)
    return page


def build_settings_page(self):
    page = QWidget()
    layout = QVBoxLayout(page)
    layout.setContentsMargins(0, 0, 0, 0)
    frame, contents = card("Captura e desempenho", "Os ajustes são aplicados com a captura parada.")
    form = QFormLayout()
    form.setSpacing(18)
    self.queue_spin = QSpinBox()
    self.queue_spin.setRange(2, 64)
    self.queue_spin.setValue(self.settings.queue_capacity)
    self.queue_spin.setSuffix(" blocos")
    self.silence_spin = QDoubleSpinBox()
    self.silence_spin.setRange(-100, -20)
    self.silence_spin.setValue(self.settings.silence_db)
    self.silence_spin.setSuffix(" dBFS")
    self.fps_spin = QSpinBox()
    self.fps_spin.setRange(15, 60)
    self.fps_spin.setValue(self.settings.ui_fps)
    self.fps_spin.setSuffix(" FPS")
    form.addRow("Capacidade da fila", self.queue_spin)
    form.addRow("Limiar de silêncio", self.silence_spin)
    form.addRow("Atualização da interface", self.fps_spin)
    contents.addLayout(form)
    contents.addWidget(label("Sobrecarga: descartar o bloco mais antigo e contar a perda. A UI recebe apenas snapshots reduzidos.", "muted", True))
    self.apply_button = QPushButton("Salvar ajustes")
    self.apply_button.setObjectName("primary")
    self.apply_button.clicked.connect(self._apply_settings)
    layout.addWidget(frame)
    layout.addWidget(build_dsp_settings(self))
    layout.addWidget(build_kick_settings(self))
    layout.addWidget(build_beat_settings(self))
    layout.addWidget(self.apply_button, 0, Qt.AlignmentFlag.AlignRight)
    self.settings_notice = label("Salve os ajustes antes de iniciar outra sessão de captura.", "notice", True)
    layout.addWidget(self.settings_notice)
    storage, storage_layout = card("Preferências locais", "JSON versionado • formato v13 · migração de v1 a v12")
    storage_layout.addWidget(label(str(self.store.path), "muted", True))
    row = QHBoxLayout()
    self.import_button = QPushButton("Importar preferências")
    self.import_button.clicked.connect(self._import_settings)
    export_button = QPushButton("Exportar preferências")
    export_button.clicked.connect(self._export_settings)
    row.addWidget(self.import_button)
    row.addWidget(export_button)
    row.addStretch()
    storage_layout.addLayout(row)
    layout.addWidget(storage)
    layout.addWidget(label("Escopo desta versão: captura, DSP, kicks, Beat Tracker e iluminação abstrata. Ajustes de luz ficam em Lighting Studio. O palco virtual inclui Show rítmico; editor de cenas e saída DMX seguem nas próximas fases.", "notice", True))
    layout.addStretch()
    scroll = QScrollArea()
    scroll.setWidgetResizable(True)
    scroll.setWidget(page)
    return scroll
